"""
LLM testee runner for benchmark execution.

Integrates LLM providers, task presenters, and response parsers
to enable LLMs to complete benchmark tasks.
"""
import logging
from typing import Dict, Any, Optional
from benchmark.testee.base import BaseTestee
from benchmark.llm.providers import LLMProvider
from benchmark.llm.presenter import LLMTaskPresenter
from benchmark.llm.parser import LLMResponseParser
from benchmark.models.task import TaskDefinition
from benchmark.models.submission import Submission

logger = logging.getLogger(__name__)


class LLMTestee(BaseTestee):
    """
    LLM testee that uses language models to generate network configurations.
    
    Integrates:
    - Task presentation (formats tasks for LLM consumption)
    - LLM provider (generates responses)
    - Response parsing (extracts submissions from LLM text)
    """

    def __init__(
        self,
        provider: LLMProvider,
        testee_id: str = "llm_testee",
        rate_limit_delay: float = 1.0,
    ):
        """
        Initialize LLM testee.
        
        Args:
            provider: LLMProvider instance for generating responses
            testee_id: Unique identifier for this testee
            rate_limit_delay: Delay between requests (seconds)
        """
        self.provider = provider
        self.testee_id = testee_id
        self.rate_limit_delay = rate_limit_delay

        # Initialize presenter and parser
        self.presenter = LLMTaskPresenter()
        self.parser = LLMResponseParser()

        # Tracking
        self.requests_made = 0

    def generate_submission(
        self,
        task: TaskDefinition,
        task_index: Optional[int] = None,
        total_tasks: Optional[int] = None,
    ) -> Submission:
        """
        Generate a configuration submission using the LLM.
        
        Args:
            task: TaskDefinition to generate submission for
            task_index: Optional task number in sequence
            total_tasks: Optional total number of tasks
        
        Returns:
            Submission generated by the LLM
        
        Raises:
            ValueError: If LLM response cannot be parsed
            Exception: If LLM API call fails
        """
        logger.info(f"Generating submission for task {task.task_id} using LLM")

        # Format task as prompt
        prompt = self.presenter.format_task_for_llm(
            task, task_index=task_index, total_tasks=total_tasks
        )

        logger.debug(f"Prompt length: {len(prompt)} characters")

        # Get response from LLM
        try:
            response = self.provider.generate_response(prompt)
            self.requests_made += 1

            logger.info(
                f"Received LLM response ({len(response)} characters) "
                f"for task {task.task_id}"
            )

        except Exception as e:
            logger.error(f"LLM API call failed for task {task.task_id}: {e}")
            raise

        # Parse response into submission
        try:
            submission = self.parser.parse_response(
                response=response,
                task_id=task.task_id,
                testee_id=self.testee_id,
            )

            logger.info(
                f"Successfully parsed submission for task {task.task_id}: "
                f"{len(submission.approach.commands)} node configurations"
            )

            return submission

        except ValueError as e:
            logger.error(f"Failed to parse LLM response for task {task.task_id}: {e}")
            raise

    def get_testee_info(self) -> Dict[str, Any]:
        """
        Get information about this LLM testee.
        
        Returns:
            Dictionary with testee metadata
        """
        model_info = self.provider.get_model_info()

        return {
            "testee_id": self.testee_id,
            "testee_type": "llm",
            "provider": model_info.get("provider"),
            "model": model_info.get("model"),
            "requests_made": self.requests_made,
            "rate_limit_delay": self.rate_limit_delay,
        }

