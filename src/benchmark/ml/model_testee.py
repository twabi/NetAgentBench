"""
ML model testee for benchmark execution.

Supports loading pre-trained ML models and running inference
to generate network configurations.

NOTE: This is an inference-only interface. Training is done externally.
"""
import logging
import json
from abc import abstractmethod
from typing import Dict, Any, Optional
from pathlib import Path
from benchmark.testee.base import BaseTestee
from benchmark.models.task import TaskDefinition
from benchmark.models.submission import Submission

logger = logging.getLogger(__name__)


class MLModelTestee(BaseTestee):
    """
    Abstract base class for ML model testees.
    
    Loads pre-trained models and runs inference to generate configurations.
    Subclasses implement framework-specific loading and inference.
    
    NOTE: This interface is for INFERENCE ONLY. Models must be trained
    externally and saved to checkpoint files.
    """

    def __init__(
        self,
        model_path: str,
        testee_id: str = "ml_model",
        framework: str = "unknown",
    ):
        """
        Initialize ML model testee.
        
        Args:
            model_path: Path to saved model checkpoint
            testee_id: Unique identifier for this testee
            framework: ML framework (pytorch, tensorflow, onnx, etc.)
        """
        self.model_path = Path(model_path)
        self.testee_id = testee_id
        self.framework = framework

        # Validate model file exists
        if not self.model_path.exists():
            raise FileNotFoundError(f"Model not found: {model_path}")

        # Load model (implemented by subclasses)
        self._load_model()

        logger.info(f"Loaded {framework} model from {model_path}")

    @abstractmethod
    def _load_model(self):
        """
        Load the model from checkpoint.
        
        Implemented by framework-specific subclasses.
        """
        pass

    @abstractmethod
    def _run_inference(self, task: TaskDefinition) -> Dict[str, Any]:
        """
        Run model inference on the task.
        
        Args:
            task: TaskDefinition to generate configuration for
        
        Returns:
            Dictionary with 'approach' key containing configuration
        
        Implemented by framework-specific subclasses.
        """
        pass

    def generate_submission(self, task: TaskDefinition) -> Submission:
        """
        Generate a configuration submission using ML model inference.
        
        Args:
            task: TaskDefinition to generate submission for
        
        Returns:
            Submission generated by the ML model
        """
        logger.info(f"Running ML model inference for task {task.task_id}")

        # Run inference
        try:
            result = self._run_inference(task)

            if "approach" not in result:
                raise ValueError("Model output missing 'approach' key")

            # Build submission
            submission = Submission(
                task_id=task.task_id,
                testee_id=self.testee_id,
                testee_type="ml_model",
                approach=result["approach"],
            )

            logger.info(
                f"ML model generated submission for task {task.task_id}: "
                f"{len(submission.approach.commands)} node configurations"
            )

            return submission

        except Exception as e:
            logger.error(f"ML model inference failed for task {task.task_id}: {e}")
            raise

    def get_testee_info(self) -> Dict[str, Any]:
        """
        Get information about this ML model testee.
        
        Returns:
            Dictionary with testee metadata
        """
        return {
            "testee_id": self.testee_id,
            "testee_type": "ml_model",
            "framework": self.framework,
            "model_path": str(self.model_path),
        }


class MockMLModelTestee(MLModelTestee):
    """
    Mock ML model testee for testing.
    
    Simulates a trained model without requiring actual ML frameworks.
    """

    def __init__(self, model_path: str, testee_id: str = "mock_ml_model"):
        """
        Initialize mock ML model.
        
        Args:
            model_path: Path to mock model file
            testee_id: Unique identifier
        """
        # Create mock model file if it doesn't exist
        model_path_obj = Path(model_path)
        if not model_path_obj.exists():
            model_path_obj.parent.mkdir(parents=True, exist_ok=True)
            model_path_obj.write_text("{}")

        super().__init__(
            model_path=model_path,
            testee_id=testee_id,
            framework="mock",
        )

    def _load_model(self):
        """Load mock model (no-op)."""
        self.model = {"type": "mock", "version": "1.0"}
        logger.debug("Loaded mock ML model")

    def _run_inference(self, task: TaskDefinition) -> Dict[str, Any]:
        """
        Run mock inference.
        
        Args:
            task: TaskDefinition
        
        Returns:
            Mock configuration output
        """
        # Generate simple mock commands for all nodes
        commands = []
        for node in task.topology.nodes:
            commands.append({
                "node": node.name,
                "commands": [f"# Mock ML model config for {node.name}"]
            })

        return {
            "approach": {
                "description": "Mock ML model generated configuration",
                "commands": commands
            }
        }

